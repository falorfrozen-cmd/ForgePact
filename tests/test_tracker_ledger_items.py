#!/usr/bin/env python3
"""The tracker's item and room table against HS Offline Tracker's `items.rs`
and `items.js`, and the item codex built on it.

`src/forgepact_tracker/item_table.py` is generated by
`tools/gen_tracker_items.py` from `HS-Offline-Tracker/src-tauri/src/items.rs`
(its `ITEMS`, `RARITY_BY_NAME`, `TIER_BY_NAME`, `MUDDLED`, `BY_ID` and
`ROOMS`) and `HS-Offline-Tracker/src/items.js` (its `DROP_RATE`,
`DROP_ZONES`, `DROP_CHASE`, `DROP_PLACES`, `TYPE_NAMES` and `WEAPON_NAMES`,
which only the codex reads). The committed module must be exactly what the
generator makes of the Tracker checkout beside it, every Rust table must hold
as many entries as its declaration says, and every `items.js` table must equal
what this file reads out of `items.js` by its own, simpler means. The codex's
rows must be what the Tracker's own `Codex.svelte` builds from `items.js`.
When the Tracker checkout is absent (a standalone ForgePact clone) the
comparisons skip and say so; the lookups and the codex's shape are still
checked against the committed module.
"""

import importlib
import json
import re
import sys
import unittest
from pathlib import Path

TESTS = Path(__file__).resolve().parent
FORGEPACT = TESTS.parent
sys.path.insert(0, str(TESTS))
sys.path.insert(0, str(FORGEPACT / "src"))
sys.path.insert(0, str(FORGEPACT / "tools"))

import gen_tracker_items  # noqa: E402
from forgepact_tracker import codex, item_table, items  # noqa: E402

ITEMS_RS = FORGEPACT.parent / "HS-Offline-Tracker" / "src-tauri" / "src" / "items.rs"
ITEMS_JS = FORGEPACT.parent / "HS-Offline-Tracker" / "src" / "items.js"
MODULE = FORGEPACT / "src" / "forgepact_tracker" / "item_table.py"


def js_json_table(text, name):
    """One `export const NAME = <JSON>;` table of items.js, read plainly."""
    m = re.search(r"^export const %s = (\{.*\});$" % name, text, re.M)
    return json.loads(m.group(1))


def js_object_table(text, name):
    """One `export const NAME = { 0: 'x', ... };` table of items.js, read plainly."""
    body = re.search(r"^export const %s = \{\n(.*?)\n\};$" % name, text, re.M | re.S).group(1)
    return {int(k): v for k, v in re.findall(r"(\d+): '([^']*)'", body)}


def js_items(text):
    """items.js's ITEMS, with the rows its `Object.assign(ITEMS, {...})` adds,
    in the order the Tracker's codex iterates them."""
    found = js_json_table(text, "ITEMS")
    block = re.search(r"^Object\.assign\(ITEMS, \{\n(.*?)\n\}\);$", text, re.M | re.S).group(1)
    for key, name in re.findall(r"'(\d+:\d+:\d+)': '([^']*)'", block):
        found[key] = name
    return found


class GeneratedTableTests(unittest.TestCase):
    def setUp(self):
        if not ITEMS_RS.is_file() or not ITEMS_JS.is_file():
            self.skipTest("HS-Offline-Tracker's items.rs or items.js is absent; the comparison needs the "
                          "Tracker checkout beside ForgePact")

    def test_the_committed_module_is_what_the_generator_makes_of_items_rs_and_items_js(self):
        text = ITEMS_RS.read_text(encoding="utf-8")
        js = ITEMS_JS.read_text(encoding="utf-8")
        self.assertEqual(gen_tracker_items.render(text, js), MODULE.read_text(encoding="utf-8"),
                         "run `py -3 ForgePact/tools/gen_tracker_items.py` and commit the result")

    def test_every_table_holds_what_the_rust_declaration_says(self):
        tables = gen_tracker_items.parse(ITEMS_RS.read_text(encoding="utf-8"))
        declared = gen_tracker_items.declared_lengths(ITEMS_RS.read_text(encoding="utf-8"))
        self.assertEqual(set(declared), {"ITEMS", "RARITY_BY_NAME", "TIER_BY_NAME", "MUDDLED", "BY_ID", "ROOMS"})
        for name, count in declared.items():
            self.assertEqual(len(tables[name]), count, name)
        module = importlib.reload(item_table)
        self.assertEqual(len(module.ITEMS), declared["ITEMS"])
        self.assertEqual(len(module.RARITY_BY_NAME), declared["RARITY_BY_NAME"])
        self.assertEqual(len(module.TIER_BY_NAME), declared["TIER_BY_NAME"])
        self.assertEqual(len(module.MUDDLED), declared["MUDDLED"])
        self.assertEqual(len(module.BY_ID), declared["BY_ID"])
        self.assertEqual(len(module.ROOMS), declared["ROOMS"])

    def test_the_generator_refuses_a_line_it_cannot_read(self):
        text = ITEMS_RS.read_text(encoding="utf-8").replace('(0, "Harlequinn\'s Crest"),',
                                                            '(0, Harlequinn),', 1)
        with self.assertRaises(ValueError):
            gen_tracker_items.parse(text)


class ItemsJsTableTests(unittest.TestCase):
    """The six tables the codex reads, against items.js itself."""

    def setUp(self):
        if not ITEMS_JS.is_file():
            self.skipTest("HS-Offline-Tracker/src/items.js is absent; the comparison needs the "
                          "Tracker checkout beside ForgePact")
        self.js = ITEMS_JS.read_text(encoding="utf-8")

    def test_the_drop_tables_equal_items_js_entry_for_entry_and_in_order(self):
        module = importlib.reload(item_table)
        for name in ("DROP_RATE", "DROP_ZONES", "DROP_CHASE", "DROP_PLACES"):
            expected = js_json_table(self.js, name)
            table = getattr(module, name)
            self.assertEqual([k for k, _ in table], list(expected), name)
            self.assertEqual({k: (list(v) if isinstance(v, tuple) else v) for k, v in table}, expected, name)
        self.assertGreater(len(module.DROP_RATE), 800, "the general chances are most of the named items")

    def test_the_type_and_weapon_labels_equal_items_js(self):
        module = importlib.reload(item_table)
        self.assertEqual(dict(module.TYPE_NAMES), js_object_table(self.js, "TYPE_NAMES"))
        self.assertEqual(dict(module.WEAPON_NAMES), js_object_table(self.js, "WEAPON_NAMES"))
        self.assertEqual(dict(module.TYPE_NAMES)[0], "Helmet")
        self.assertEqual(dict(module.WEAPON_NAMES)[14], "Gun")

    def test_the_generator_refuses_what_it_cannot_read(self):
        broken = {
            "a table declared twice": self.js + "\nexport const DROP_RATE = {};\n",
            "a table missing": self.js.replace("export const DROP_CHASE = ", "export const DROP_CHASED = ", 1),
            "a key twice": self.js.replace('export const DROP_RATE = {"harlequinn\'s crest":46750,',
                                           'export const DROP_RATE = {"harlequinn\'s crest":46750,'
                                           '"harlequinn\'s crest":1,', 1),
            "a chance that is not a number": self.js.replace('"harlequinn\'s crest":46750',
                                                             '"harlequinn\'s crest":"46750"', 1),
            "a label line it cannot read": self.js.replace("  0: 'Helmet', 1: 'Chest',", "  0: Helmet, 1: 'Chest',", 1),
        }
        for why, text in broken.items():
            self.assertNotEqual(text, self.js, "the fixture for %s did not change items.js" % why)
            with self.assertRaises(ValueError, msg=why):
                gen_tracker_items.parse_js(text)


class CodexTests(unittest.TestCase):
    """`forgepact_tracker/codex.py`, the rows `/api/tracker/codex` answers."""

    FIELDS = {"name", "rarity", "tier", "type", "group", "rate", "chase", "zones", "places"}

    def test_a_row_says_what_the_item_is_and_where_to_farm_it(self):
        rows = {r["name"]: r for r in codex.rows()}
        avenger = rows["The Colossal Avenger"]
        self.assertEqual(set(avenger), self.FIELDS)
        self.assertEqual((avenger["rarity"], avenger["tier"], avenger["type"], avenger["group"]),
                         ("Heroic", 6, "Helmet", "Helmet"))
        self.assertGreater(avenger["chase"], 0, "tied to a place, with the better chance there")
        self.assertTrue(avenger["zones"] and avenger["places"])
        gun = rows["Ethereal Musket"]
        self.assertEqual((gun["type"], gun["group"]), ("Gun", "Weapon"), "a weapon is labelled by its own kind")

    def test_one_row_per_name_and_no_blank_place(self):
        rows = codex.rows()
        names = [r["name"] for r in rows]
        self.assertEqual(len(names), len(set(names)))
        self.assertEqual(len(rows), len({name for _, name in item_table.ITEMS}))
        for row in rows:
            self.assertTrue(all(row["places"]), row["name"])
            self.assertTrue(all(row["zones"]), row["name"])
        holster = next(r for r in rows if r["name"].lower() == "liquor holster")
        self.assertEqual(holster["places"], [], "the table's one blank place is left out")

    def test_each_call_answers_its_own_copy(self):
        first = codex.rows()
        first[0]["zones"].append("changed")
        first[0]["name"] = "changed"
        self.assertNotEqual(codex.rows()[0]["name"], "changed")
        self.assertNotIn("changed", codex.rows()[0]["zones"])

    def test_the_rows_are_what_the_trackers_codex_builds_from_items_js(self):
        if not ITEMS_JS.is_file():
            self.skipTest("HS-Offline-Tracker/src/items.js is absent")
        js = ITEMS_JS.read_text(encoding="utf-8")
        rarity = js_json_table(js, "RARITY_BY_NAME")
        tier = js_json_table(js, "TIER_BY_NAME")
        rate, chase = js_json_table(js, "DROP_RATE"), js_json_table(js, "DROP_CHASE")
        zones, places = js_json_table(js, "DROP_ZONES"), js_json_table(js, "DROP_PLACES")
        types, weapons = js_object_table(js, "TYPE_NAMES"), js_object_table(js, "WEAPON_NAMES")
        expected = {}
        # Codex.svelte's CATALOGUE: the first sighting of a name wins
        for key, name in js_items(js).items():
            if name in expected:
                continue
            item_type, _, weapon = (int(p) for p in key.split(":"))
            k = name.lower()
            group = types.get(item_type, "Type %d" % item_type)
            expected[name] = {
                "name": name, "rarity": rarity.get(k, ""), "tier": tier.get(k, 0),
                "type": weapons.get(weapon, "Weapon %d" % weapon) if item_type == 3 and weapon > 0 else group,
                "group": group, "rate": rate.get(k, 0), "chase": chase.get(k, 0),
                "zones": [z for z in zones.get(k, []) if z], "places": [p for p in places.get(k, []) if p],
            }
        self.assertEqual({r["name"]: r for r in codex.rows()}, expected)


class LookupTests(unittest.TestCase):
    """`items.rs`'s own test and the lookups `stats.rs` leans on, against the
    committed module."""

    def test_all_season_10_heroic_identities_resolve_as_ss(self):
        expected = [
            (0, 89, 0, "Parasite Queen´s Tiara"), (0, 90, 0, "Leviathan´s Crown"),
            (1, 103, 0, "Captain´s Attire"), (1, 104, 0, "Leviathan´s Ribcage"),
            (2, 81, 0, "Ghostplunderer´s Marchers"), (2, 82, 0, "Phantom´s Step"),
            (3, 36, 1, "Grimtide´s Scimitar"), (3, 37, 1, "Phantom Scimitar"),
            (3, 8, 9, "Leviathan´s Spine"), (3, 13, 10, "Conjured Tentacle"),
            (3, 20, 13, "Phantom Strike"), (3, 19, 14, "Ethereal Musket"),
            (4, 65, 0, "Infected Grasp"), (5, 75, 0, "Grimtide´s Necklace"),
            (5, 76, 0, "Blood Maggot Pendant"), (6, 56, 0, "Overgrowth"),
            (7, 60, 0, "Skeleton Crew´s Band"), (7, 61, 0, "Parasite Loop"),
            (10, 99, 0, "Captain´s Anchor"), (10, 100, 0, "Ghastly Skull"),
            (10, 101, 0, "Parasitic Heart"), (10, 102, 0, "Ghost Armada"),
            (10, 103, 0, "Jar of Parasites"), (18, 22, 0, "Leviathan´s Blood"),
        ]
        for item_type, item_id, weapon_type, name in expected:
            self.assertEqual(items.item_name(item_type, item_id, weapon_type), name)
            self.assertEqual(items.rarity_by_name(name), "Heroic", name)
            self.assertEqual(items.tier_by_name(name), 6, name)

    def test_an_identity_tells_apart_what_a_name_cannot(self):
        self.assertTrue(items.muddled("Angel"))
        self.assertIsNone(items.rarity_by_name("Angel"))
        gun = items.known_by_identity(3, 11, 14)
        orb = items.known_by_identity(15, 116, 0)
        self.assertEqual((gun.name, gun.rarity, gun.tier), ("Angel", "Set", 5))
        self.assertEqual((orb.name, orb.rarity, orb.tier), ("Angel", "Heroic", 6))
        self.assertEqual(items.known_item("angel ", (15, 116, 0)).rarity, "Heroic")
        self.assertIsNone(items.known_item("Justice", (3, 11, 14)), "an identity that names another item")
        self.assertEqual(items.resolve_rarity("Angelic", "Angel", (3, 11, 14)), "Set")
        self.assertEqual(items.resolve_rarity("Angelic", "Angel", (0, 0, 0)), "Unknown",
                         "a muddled name with no identity is not guessed")
        self.assertFalse(items.muddled("No Such Item"))

    def test_a_weapon_identity_falls_back_to_its_weapon_type_agnostic_key(self):
        self.assertEqual(items.item_name(19, 5, 7), "Essence Vault")
        self.assertIsNone(items.item_name(256, 0, 0), "out of range is no identity at all")

    def test_a_room_has_the_game_s_own_name(self):
        self.assertEqual(items.room_name("Act_01_01"), "Outskirts of Inoya")
        self.assertIsNone(items.room_name("Nowhere_rm"))


