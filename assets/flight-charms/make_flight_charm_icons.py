"""Embed the Flight charms' six icons in the plugin, or check that they match.

ForgePact #158 phase 2 (docs/flight-charms-research.md): each Flight charm
draws an icon of our own in the bag and on the ground. The six PNGs in this
directory are the owner's own art (see ICONS.md and prompts.json), never art
taken from the game. They are this script's inputs: it draws nothing and never
writes a PNG.

    py -3 assets/flight-charms/make_flight_charm_icons.py          # write the header
    py -3 assets/flight-charms/make_flight_charm_icons.py --check  # verify only

Both modes first check every PNG: an 8-bit RGBA PNG at the size the plugin
expects (the table below), whose sha256 and size match its manifest.json entry.
The default mode then writes plugin/include/ForgePact/FlightCharmIcons.hpp with
the six files' bytes. `--check` writes nothing, and exits 0 only when every PNG
passes and the header is byte for byte what this script would write.

Stdlib only. charmprobe.png and make_charmprobe_icon.py are phase 1's research
placeholder and are not read here.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import struct
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
MANIFEST = HERE / "manifest.json"
HEADER = ROOT / "plugin" / "include" / "ForgePact" / "FlightCharmIcons.hpp"

# (file, charm key, ground copy, width, height). The charm key is the verb word
# `flightcharm <word>` takes; the sizes are the workorder's table: the bag icon
# covers the charm's footprint at 32 px a cell, the ground icon is the size the
# game's own Pickup_ sprites use. Order: bag then ground, elf, wings, broom.
ICONS = (
    ("pocket_elf.png", "elf", False, 32, 32),
    ("pocket_elf_ground.png", "elf", True, 16, 16),
    ("gabriel_wings.png", "wings", False, 64, 64),
    ("gabriel_wings_ground.png", "wings", True, 24, 24),
    ("witch_broomstick.png", "broom", False, 32, 160),
    ("witch_broomstick_ground.png", "broom", True, 34, 17),
)

PNG_SIGNATURE = b"\x89PNG\r\n\x1a\n"


def png_header(data: bytes) -> tuple[int, int, int, int]:
    """Answer (width, height, bit depth, colour type) from a PNG's IHDR chunk."""
    if data[:8] != PNG_SIGNATURE or data[12:16] != b"IHDR":
        raise ValueError("not a PNG")
    width, height, depth, colour = struct.unpack(">IIBB", data[16:26])
    return width, height, depth, colour


def check_icons() -> tuple[list[tuple[str, str, bool, int, int, bytes]], list[str]]:
    """Read and check the six PNGs; answer them and every problem found."""
    problems: list[str] = []
    try:
        manifest = {entry["file"]: entry for entry in json.loads(MANIFEST.read_text(encoding="utf-8"))["assets"]}
    except (OSError, ValueError, KeyError, TypeError) as exc:
        return [], [f"{MANIFEST.name}: unreadable ({exc})"]
    icons = []
    for name, key, ground, width, height in ICONS:
        path = HERE / name
        try:
            data = path.read_bytes()
            got = png_header(data)
        except (OSError, ValueError) as exc:
            problems.append(f"{name}: unreadable ({exc})")
            continue
        if got != (width, height, 8, 6):
            problems.append(f"{name}: is {got[0]}x{got[1]} depth {got[2]} colour type {got[3]}, "
                            f"expected {width}x{height} 8-bit RGBA")
        entry = manifest.get(name)
        if entry is None:
            problems.append(f"{name}: no entry in {MANIFEST.name}")
        else:
            digest = hashlib.sha256(data).hexdigest()
            if entry.get("sha256") != digest:
                problems.append(f"{name}: sha256 {digest} does not match {MANIFEST.name}'s {entry.get('sha256')}")
            if (entry.get("width"), entry.get("height")) != (width, height):
                problems.append(f"{name}: {MANIFEST.name} says {entry.get('width')}x{entry.get('height')}, "
                                f"expected {width}x{height}")
        icons.append((name, key, ground, width, height, data))
    return icons, problems


def header_text(icons: list[tuple[str, str, bool, int, int, bytes]]) -> str:
    parts = ["// Generated by assets/flight-charms/make_flight_charm_icons.py - do not edit by hand.",
             "// The Flight charms' bag and ground icons (ForgePact #158): the owner's own art,",
             "// nothing taken from the game. Source PNGs and their manifest.json:",
             "// assets/flight-charms/. Check with `make_flight_charm_icons.py --check`.",
             "#pragma once", "#include <cstddef>", "", "namespace ForgePact::FlightCharmIcons {",
             "// file: the PNG's file name, also the name it is written under in bp_ipc\\flightcharms\\.",
             "// charm: the charm's verb word (elf, wings, broom). ground: the ground copy, else the bag icon.",
             "// width/height: the embedded PNG's size in pixels. data/size: the PNG file's bytes.",
             "struct Icon { const char* file; const char* charm; bool ground; int width; int height;",
             "              const unsigned char* data; size_t size; };"]
    for name, _key, _ground, _w, _h, data in icons:
        parts.append(f"inline constexpr unsigned char k_{Path(name).stem}[] = {{")
        parts.extend("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ","
                     for i in range(0, len(data), 16))
        parts.append("};")
    parts.append("inline constexpr Icon kIcons[] = {")
    for name, key, ground, width, height, _data in icons:
        stem = Path(name).stem
        parts.append(f'    {{ "{name}", "{key}", {"true" if ground else "false"}, {width}, {height}, '
                     f"k_{stem}, sizeof(k_{stem}) }},")
    parts.extend(["};", "inline constexpr size_t kIconCount = sizeof(kIcons) / sizeof(kIcons[0]);", "}"])
    return "\n".join(parts) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="write nothing; exit 1 unless the PNGs and the header are current")
    args = parser.parse_args(argv)

    icons, problems = check_icons()
    for problem in problems:
        print(f"FAIL {problem}", file=sys.stderr)
    if problems:
        return 1
    text = header_text(icons)
    if args.check:
        try:
            current = HEADER.read_bytes()
        except OSError as exc:
            print(f"FAIL {HEADER.name}: unreadable ({exc})", file=sys.stderr)
            return 1
        if current != text.encode("utf-8"):
            print(f"FAIL {HEADER.name} is stale: re-run make_flight_charm_icons.py", file=sys.stderr)
            return 1
        print(f"OK {len(icons)} icons match {MANIFEST.name} and {HEADER.name}")
        return 0
    HEADER.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {HEADER.name} ({len(icons)} icons, {sum(len(i[5]) for i in icons)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
