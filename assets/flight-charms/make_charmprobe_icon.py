"""Draw charmprobe's placeholder research icon and embed it in the plugin.

ForgePact #158 phase 1 (docs/flight-charms-research.md): `charmprobe sprite`
loads one PNG of our own with sprite_add, by the pack markers' route, to ask
whether a forged charm can show custom art and whether a save keeps it. This
is that PNG: a plain shape drawn here from code (a white-edged teal diamond
with a gold centre on a transparent background, 32x32 RGBA, one charm cell),
never art taken from the game. It is a research placeholder, not the Flight
charms' final art.

Stdlib only. Writes assets/flight-charms/charmprobe.png (the source asset,
kept in the tree) and plugin/include/ForgePact/FlightCharmProbeIcon.hpp (its
bytes, the way tools/make_packmark_icons.py embeds the pack marker icons).
Rerunning it reproduces both files byte for byte.
"""
from __future__ import annotations

import struct
import zlib
from pathlib import Path

SIZE = 32
HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
PNG = HERE / "charmprobe.png"
HEADER = ROOT / "plugin" / "include" / "ForgePact" / "FlightCharmProbeIcon.hpp"

TEAL = (32, 178, 170, 255)
EDGE = (255, 255, 255, 255)
GOLD = (240, 196, 64, 255)
CLEAR = (0, 0, 0, 0)


def pixel(x: int, y: int) -> tuple[int, int, int, int]:
    # Manhattan distance from the centre of the 32x32 grid (between pixels 15 and 16).
    d = abs(x - 15.5) + abs(y - 15.5)
    if d <= 4:
        return GOLD
    if d <= 12:
        return TEAL
    if d <= 14:
        return EDGE
    return CLEAR


def png_bytes() -> bytes:
    rows = b"".join(b"\x00" + b"".join(bytes(pixel(x, y)) for x in range(SIZE)) for y in range(SIZE))

    def chunk(kind: bytes, data: bytes) -> bytes:
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)

    header = struct.pack(">IIBBBBB", SIZE, SIZE, 8, 6, 0, 0, 0)   # 8-bit RGBA
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", header) + chunk(b"IDAT", zlib.compress(rows, 9))
            + chunk(b"IEND", b""))


def main() -> int:
    data = png_bytes()
    PNG.write_bytes(data)
    parts = ["// Generated by assets/flight-charms/make_charmprobe_icon.py - do not edit by hand.",
             "// charmprobe's placeholder research icon (ForgePact #158 phase 1): a plain",
             "// white-edged teal diamond with a gold centre, 32x32 RGBA, drawn by that script",
             "// from code - our own art, nothing taken from the game. Source PNG:",
             "// assets/flight-charms/charmprobe.png. Research build only: ModuleMain.cpp",
             "// includes it inside charmprobe's #ifndef FORGEPACT_RELEASE block.",
             "#pragma once", "#include <cstddef>", "", "namespace ForgePact::FlightCharmProbeIcon {",
             f"inline constexpr int kSize = {SIZE};",
             'inline constexpr const char* kName = "charmprobe";',
             "inline constexpr unsigned char kPng[] = {"]
    parts.extend("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + "," for i in range(0, len(data), 16))
    parts.extend(["};", "inline constexpr size_t kPngSize = sizeof(kPng);", "}"])
    HEADER.write_text("\n".join(parts) + "\n", encoding="utf-8", newline="\n")
    print(f"Wrote {PNG.name} ({len(data)} bytes) and {HEADER.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
