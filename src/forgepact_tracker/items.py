"""Item and room lookups over HS Offline Tracker's tables.

The behaviour of the Tracker's `items.rs` lookups and of the rarity rules in
its `parser.rs` (`known_item`, `resolve_rarity`) and `stats.rs`
(`rarity_from_packet`), ported to Python. The tables themselves are in
`item_table.py`, generated by `tools/gen_tracker_items.py`.
"""

from __future__ import annotations

from typing import NamedTuple

from . import item_table

# Rarity ids as the game numbers them, and the names the ledger counts under.
RARITIES = (
    ("1", "Common"),
    ("2", "Superior"),
    ("3", "Rare"),
    ("4", "Set"),
    ("5", "Mythic"),
    ("6", "Satanic"),
    ("7", "Angelic"),
    ("8", "Blessed"),
    ("9", "Heroic"),
    ("10", "Unholy"),
)
RARITY_NAMES = tuple(name for _, name in RARITIES)
_RARITY_BY_ID = dict(RARITIES)

_ITEMS = dict(item_table.ITEMS)
_RARITY = dict(item_table.RARITY_BY_NAME)
_TIER = dict(item_table.TIER_BY_NAME)
_MUDDLED = frozenset(item_table.MUDDLED)
_BY_ID = {key: (name, rarity, tier) for key, name, rarity, tier in item_table.BY_ID}
_ROOMS = dict(item_table.ROOMS)


class Known(NamedTuple):
    """What the tables know about one item: its name, rarity and grade
    (1 = D .. 6 = SS)."""

    name: str
    rarity: str
    tier: int


def _int(value) -> int | None:
    """A whole number from a record field. The protocol writes whole numbers
    as floats ("5.0") as often as not, so both spellings are read."""
    if isinstance(value, bool):
        return None
    if isinstance(value, int):
        return value
    if isinstance(value, float):
        return int(value) if value == value and abs(value) != float("inf") else None
    if isinstance(value, str):
        text = value.strip()
        try:
            return int(text)
        except ValueError:
            try:
                number = float(text)
            except ValueError:
                return None
            return int(number) if number == number and abs(number) != float("inf") else None
    return None


def packed(item_type: int, item_id: int, weapon_type: int) -> int | None:
    """The identity triple as the tables key it, or None when it is not one."""
    if not (0 <= item_type < 256 and 0 <= item_id < 65536 and 0 <= weapon_type < 256):
        return None
    return (item_type << 24) | (item_id << 8) | weapon_type


def _lookup(item_type: int, item_id: int, weapon_type: int) -> str | None:
    key = packed(item_type, item_id, weapon_type)
    return None if key is None else _ITEMS.get(key)


def item_name(item_type: int, item_id: int, weapon_type: int) -> str | None:
    """An item's name by identity, falling back to the weapon-type-agnostic key."""
    return _lookup(item_type, item_id, weapon_type) or _lookup(item_type, item_id, 0)


def known_by_identity(item_type: int, item_id: int, weapon_type: int) -> Known | None:
    """What an identity is, for the few items whose name cannot say (`BY_ID`)."""
    for wt in (weapon_type, 0):
        key = packed(item_type, item_id, wt)
        if key is not None and key in _BY_ID:
            name, rarity, tier = _BY_ID[key]
            return Known(name, rarity, int(tier))
    return None


def known_item(name: str, identity: tuple[int, int, int], unscaled: bool = False) -> Known | None:
    """The identity's entry, but only where it names the same item as `name`.

    An item off another rarity scale (`unscaled`) and an unnamed one are never
    answered: a triple read on another scale is not the triple these tables
    are keyed by."""
    if unscaled or not name:
        return None
    known = known_by_identity(*identity)
    if known is None or known.name.lower() != name.strip().lower():
        return None
    return known


def muddled(name: str) -> bool:
    """Whether the tables refuse this name on purpose: two items answer to it."""
    return name.strip().lower() in _MUDDLED


def rarity_by_name(name: str) -> str | None:
    """A named item's rarity; names are matched lower-cased."""
    return _RARITY.get(name.strip().lower())


def tier_by_name(name: str) -> int:
    """A named item's grade, 1 = D .. 6 = SS, or 0 when the tables do not grade it."""
    return int(_TIER.get(name.strip().lower(), 0))


def room_name(room: str) -> str | None:
    """What the game calls a room asset (`Act_05_03` is Fuji Coast)."""
    return _ROOMS.get(room)


def rarity_from_packet(rarity) -> str | None:
    """The rarity a record claims, if it maps to a known one: a game rarity id
    (as a number, a float or a string) or a rarity name in any case."""
    number = _int(rarity)
    if number is not None:
        key = str(number)
    elif isinstance(rarity, str):
        key = rarity.strip()
    else:
        return None
    if key in _RARITY_BY_ID:
        return _RARITY_BY_ID[key]
    if not key or _int(key) is not None:
        return None
    titled = key[:1].upper() + key[1:].lower()
    return titled if titled in RARITY_NAMES else None


def resolve_rarity(packet, name: str, identity: tuple[int, int, int], unscaled: bool = False) -> str:
    """The rarity a drop is counted under.

    The identity first, where it names the item; then the item's own rarity
    from the name table; nothing for a name two items share; and the record's
    own claim only for an item the tables have never heard of. A record's
    rarity field is the weakest of the four, which is why it comes last."""
    known = known_item(name, identity, unscaled)
    if known is not None and known.rarity:
        return known.rarity
    if name and not unscaled:
        by_name = rarity_by_name(name)
        if by_name is not None:
            return by_name
    if muddled(name):
        return "Unknown"
    return rarity_from_packet(packet) or "Unknown"
